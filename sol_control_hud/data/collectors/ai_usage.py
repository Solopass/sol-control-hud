"""Collector for AI Usage (Claude Code / Desktop and Google Antigravity).

Reads the latest summary generated by AI Usage Tracker (D:\\Workspace\\AI Usage Tracker\\latest_summary.json).
"""
from __future__ import annotations

import datetime
import json
import os
from pathlib import Path

SUMMARY_FILE = Path(
    os.environ.get(
        "AI_TRACKER_SUMMARY_JSON",
        r"D:\Workspace\AI Usage Tracker\latest_summary.json",
    )
)


def get_ai_usage() -> dict:
    """Returns today's and this week's AI usage overview for dashboard consumption."""
    if not SUMMARY_FILE.exists():
        return {
            "available": False,
            "why": "AI Usage Tracker summary not found yet (run tracker ingest).",
        }

    try:
        data = json.loads(SUMMARY_FILE.read_text(encoding="utf-8"))
    except Exception as e:
        return {"available": False, "why": f"Could not read AI usage summary: {e}"}

    today_str = datetime.date.today().isoformat()
    daily_map = data.get("daily", {})
    today_data = daily_map.get(today_str, {})
    weekly_totals = data.get("weekly_totals", {})

    today_providers = today_data.get("providers", {})
    claude_today = today_providers.get("claude", {})
    ag_today = today_providers.get("antigravity", {})

    return {
        "available": True,
        "week_id": data.get("week_id", ""),
        "last_updated": data.get("last_updated", ""),
        "weekly": {
            "total_turns": weekly_totals.get("total_turns", 0),
            "claude_tokens": weekly_totals.get("claude", {}).get("exact_tokens", 0),
            "claude_turns": weekly_totals.get("claude", {}).get("turns", 0),
            "antigravity_tokens": weekly_totals.get("antigravity", {}).get("estimated_tokens", 0),
            "antigravity_turns": weekly_totals.get("antigravity", {}).get("turns", 0),
        },
        "today": {
            "date": today_str,
            "has_activity": bool(today_providers),
            "claude": {
                "turns": claude_today.get("turn_count", 0),
                "input_tokens": claude_today.get("input_tokens", 0),
                "output_tokens": claude_today.get("output_tokens", 0),
                "cache_read_tokens": claude_today.get("cache_read_tokens", 0),
                "cache_write_tokens": claude_today.get("cache_write_tokens", 0),
                "thinking_tokens": claude_today.get("thinking_tokens", 0),
                "tool_calls": claude_today.get("tool_calls", 0),
            },
            "antigravity": {
                "turns": ag_today.get("turn_count", 0),
                "estimated_tokens": ag_today.get("input_tokens", 0) + ag_today.get("output_tokens", 0),
                # exact since tracker schema 3 (2026-11-24): Antigravity's own per-call counts
                "output_tokens": ag_today.get("output_tokens", 0),
                "input_tokens": ag_today.get("input_tokens", 0),
                "cache_read_tokens": ag_today.get("cache_read_tokens", 0),
                "is_estimated": bool(ag_today.get("is_estimated", True)),
                "tool_calls": ag_today.get("tool_calls", 0),
            },
            "models": today_data.get("models", []),
            "projects": today_data.get("projects", []),
        },
        # long-term (tracker 2026-11-23): weekly / monthly totals and Claude's 5-hour usage windows
        "history": data.get("history") or {"weeks": [], "months": []},
        "windows": data.get("windows") or {},
    }
